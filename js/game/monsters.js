function spriteFor(muscle, form) {
  const forms = MONSTERS[muscle]?.forms;
  if (!forms) return PLACEHOLDER;
  return forms[Math.max(0, Math.min(forms.length - 1, form | 0))];
}

const svgCache = new Map();

function spriteRects({ grid, palette }) {
  let out = '';
  grid.forEach((row, y) => {
    for (let x = 0; x < row.length; ) {
      const c = row[x];
      let end = x + 1;
      while (end < row.length && row[end] === c) end++;
      if (c !== '.' && palette[c]) out += `<rect x="${x}" y="${y}" width="${end - x}" height="1" fill="${palette[c]}"/>`;
      x = end;
    }
  });
  return out;
}

/** SVG string for a monster form. Unknown muscles get a neutral placeholder. */
export function monsterSprite(muscle, form = 0, size = 96, cls = '') {
  const sprite = spriteFor(muscle, form);
  let rects = svgCache.get(sprite);
  if (!rects) svgCache.set(sprite, (rects = spriteRects(sprite)));
  const c = String(cls).replace(/[^\w\s-]/g, '');
  return `<svg class="monster${c ? ' ' + c : ''}" width="${size}" height="${size}" viewBox="0 0 24 24" shape-rendering="crispEdges" xmlns="http://www.w3.org/2000/svg" aria-hidden="true">${rects}</svg>`;
}

/** Display name of a monster form; a nickname in `nicknames[muscle]` wins. */
export function monsterName(muscle, form = 0, nicknames = {}) {
  const nick = nicknames?.[muscle];
  if (typeof nick === 'string' && nick.trim()) return nick.trim();
  return spriteFor(muscle, form).name;
}
